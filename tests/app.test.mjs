import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';

let browser;
const errors=[];
before(async()=>{browser=await chromium.launch({channel:'chrome',headless:true});});
after(async()=>{await browser?.close();});
async function fresh(options={}) {
  const context=await browser.newContext({viewport:{width:1440,height:1100},...options});
  const page=await context.newPage();
  await page.route('**/api/**',route=>route.fulfill({status:404,body:'Local UI test'}));
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://localhost:4173');
  await page.locator('.post-card').first().waitFor();
  await page.evaluate(()=>document.fonts.ready);
  return {page,context};
}
test('Desktop: seeded community, brand fonts and stable layout',async()=>{
  const {page,context}=await fresh();
  assert.equal(await page.locator('.post-card').count(),6);
  assert.equal(await page.locator('.sidebar').isVisible(),true);
  assert.equal(await page.evaluate(()=>document.fonts.check('700 16px Jumbo')),true);
  assert.equal(await page.locator('.brand img').evaluate(img=>img.complete&&img.naturalWidth>0),true);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await mkdir('test-results',{recursive:true});
  await page.screenshot({path:'test-results/desktop.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await context.close();
});
test('Upvoting toggles once and survives reload',async()=>{
  const {page,context}=await fresh();
  const vote=page.locator('[data-post="p1"] .vote-button');
  const initial=Number(await vote.locator('strong').textContent());
  await vote.click();
  assert.equal(await vote.getAttribute('aria-pressed'),'true');
  assert.equal(Number(await vote.locator('strong').textContent()),initial+1);
  await page.reload();
  assert.equal(await vote.getAttribute('aria-pressed'),'true');
  await vote.click();
  assert.equal(Number(await vote.locator('strong').textContent()),initial);
  await context.close();
});
