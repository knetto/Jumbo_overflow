test('Fork keeps the original unchanged, persists content and downloads the real file',async()=>{
  const {page,context}=await fresh();
  await page.locator('a.nav-link[href="#templates"]').click();
  await page.locator('.template-card [data-action="template"]').first().click();
  const original=await page.locator('.template-preview').textContent();
  await page.getByRole('button',{name:'Pas aan voor mijn filiaal'}).click();
  await page.locator('#fork-title').fill('Avondoverdracht Dordrecht');
  await page.locator('#fork-content').fill('# Ons eigen plan\n\nDit is een aangepast template voor ons filiaal.');
  await page.getByRole('button',{name:'Bewaar mijn versie'}).click();
  await page.locator('.template-preview').waitFor();
  assert.match(await page.locator('.template-preview').textContent(),/Ons eigen plan/);
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download MD',exact:true}).click();
  const download=await downloadPromise;
  assert.match(download.suggestedFilename(),/avondoverdracht-dordrecht.md/);
  const stream=await download.createReadStream();let body='';for await(const part of stream)body+=part.toString();
  assert.match(body,/Ons eigen plan/);
  await page.getByRole('button',{name:'Venster sluiten'}).click();
  await page.reload();
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('jumbooverflow.v1')));
  assert.equal(stored.templates.length,13);
  assert.equal(stored.templates.find(t=>t.id==='t1').content,original);
  assert.equal(stored.templates.find(t=>t.title==='Avondoverdracht Dordrecht').parentId,'t1');
  await context.close();
});
